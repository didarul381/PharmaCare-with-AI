/**
 * Generates resources/css/theme.css — the CSS variables behind PharmaCare's
 * light & dark themes.
 *
 * Every neutral (`slate`, `white`) and accent palette used by the UI is
 * exposed as `rgb(var(--<palette>-<shade>) / <alpha>)` in tailwind.config.js.
 * Dark theme = stock Tailwind values. Light theme = the scale flipped so the
 * same class names stay readable on a light background.
 *
 *   node scripts/generate-theme.cjs
 */
const fs = require('fs');
const path = require('path');
const colors = require('tailwindcss/colors');

const ACCENTS = ['emerald', 'teal', 'cyan', 'sky', 'blue', 'indigo', 'violet', 'purple', 'fuchsia', 'pink', 'rose', 'red', 'orange', 'amber', 'yellow', 'lime', 'green'];
const SHADES = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];

// Accents: light text shades (300/400) become deep shades so they pass contrast on white;
// dark tints (800–950) become pale tints.
const ACCENT_LIGHT = { 50: '950', 100: '950', 200: '900', 300: '800', 400: '700', 500: '600', 600: '700', 700: '800', 800: '200', 900: '100', 950: '50' };

// Slate (the only neutral the UI uses): hand-tuned light scale.
//  950 = page/input wells, 900 = cards, 800 = borders, 400–600 = muted text, 50–200 = headings.
const SLATE_LIGHT = {
    50: '#0b1220', 100: '#131c2e', 200: '#1e293b', 300: '#334155', 400: '#475569',
    500: '#5b6b81', 600: '#8492a6', 700: '#cbd5e1', 800: '#e2e8f0', 900: '#ffffff', 950: '#f1f5f9',
};

const rgb = (hex) => {
    const h = hex.replace('#', '');
    const n = parseInt(h.length === 3 ? h.split('').map((c) => c + c).join('') : h, 16);
    return `${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255}`;
};

const SURFACES = {
    //            dark        light
    canvas: ['#0b0f19', '#f4f6fa'], // app background
    deep: ['#070b13', '#eef2f7'],   // recessed panels / gradient ends
    panel: ['#0d1322', '#ffffff'],  // raised panels / modals
};

function block(mode) {
    const lines = [];
    for (const s of SHADES) lines.push(`--slate-${s}: ${rgb(mode === 'dark' ? colors.slate[s] : SLATE_LIGHT[s])};`);
    lines.push(`--white: ${mode === 'dark' ? '255 255 255' : rgb(SLATE_LIGHT[50])};`);
    // Label colour on solid accent buttons: dark ink on bright dark-theme accents, white on deeper light-theme accents.
    lines.push(`--ink: ${mode === 'dark' ? '2 6 23' : '255 255 255'};`);
    for (const a of ACCENTS) {
        for (const s of SHADES) lines.push(`--${a}-${s}: ${rgb(colors[a][mode === 'dark' ? s : ACCENT_LIGHT[s]])};`);
    }
    for (const [name, [dark, light]] of Object.entries(SURFACES)) lines.push(`--${name}: ${rgb(mode === 'dark' ? dark : light)};`);
    lines.push(mode === 'dark'
        ? '--shadow-glass: 0 8px 32px 0 rgba(0, 0, 0, 0.37);\n    --backdrop: 2 6 23;\n    --backdrop-alpha: 0.8;\n    color-scheme: dark;'
        : '--shadow-glass: 0 8px 24px -6px rgba(15, 23, 42, 0.10), 0 2px 6px -2px rgba(15, 23, 42, 0.06);\n    --backdrop: 15 23 42;\n    --backdrop-alpha: 0.45;\n    color-scheme: light;');
    return lines.map((l) => `    ${l}`).join('\n');
}

const css = `/* AUTO-GENERATED by scripts/generate-theme.cjs — edit that file, not this one. */

/* Light theme (default when <html> has no .dark class) */
:root {
${block('light')}
}

/* Dark theme. .stock-colors pins stock Tailwind colours (receipt / paper previews) in either theme. */
.dark,
.stock-colors {
${block('dark')}
}

/* Printed receipts always use stock colours on white paper. */
@media print {
    :root {
${block('dark').replace(/    color-scheme: dark;/, '    color-scheme: light;')}
    }
}
`;

fs.writeFileSync(path.join(__dirname, '..', 'resources', 'css', 'theme.css'), css);
console.log('wrote resources/css/theme.css');

module.exports = { ACCENTS, SHADES };
